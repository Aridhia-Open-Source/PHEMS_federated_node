#!/usr/bin/env bash
set -euo pipefail

###############################################################################
# Runs real experiments against the dev federated node. See experiments/README.md.
#
#   up               install/upgrade the experiments release (a database per project)
#   down             uninstall it (secrets and database files stay)
#   seed NAME        load the project's dummy data and set up its node project with fncli
#   build NAME       build the project's image and push it to the kind registry
#   run NAME         open and merge a trigger PR for the image, and watch the task
#   run-local NAME   run the image in docker against the database, no node involved
#
# run and run-local pass the project's DEV_ENV to the task; FULL=1 leaves it out.
###############################################################################

EXP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(dirname "$EXP_DIR")"
NAMESPACE=experiments
RELEASE=experiments
FN_DATA_DIR="${FN_DATA_DIR:-$HOME/.fn/data}"
# Host port for run-local's port-forward. 5432 is the node's own Postgres.
LOCAL_PORT="${EXPERIMENTS_LOCAL_PORT:-5434}"

usage() {
  sed -n '/^#   [a-z]/s/^#   //p' "$0"
  exit 1
}

load_project() {
  local name="${1:?project name required}"
  PROJECT_DIR="$EXP_DIR/projects/$name"
  if [ ! -f "$PROJECT_DIR/project.env" ]; then
    echo "No such project: $PROJECT_DIR/project.env" >&2
    exit 1
  fi
  set -a
  source "$PROJECT_DIR/project.env"
  set +a
}

# The task env for this run, as JSON: the project's DEV_ENV unless FULL=1.
task_env() {
  if [ "${FULL:-}" = "1" ]; then
    echo "{}"
  else
    echo "${DEV_ENV:-{\}}"
  fi
}

# Generated by the chart, so read back from its secret.
load_password() {
  DATASET_PASSWORD=$(kubectl get secret "$DATASET_SECRET_NAME" -n "$NAMESPACE" \
    -o jsonpath='{.data.password}' | base64 -d)
  export DATASET_PASSWORD
}

up() {
  local host_dir="$FN_DATA_DIR/experiments/datasets"
  if [ ! -d "$FN_DATA_DIR" ]; then
    echo "$FN_DATA_DIR does not exist - run ./scripts/cluster.sh up first" >&2
    exit 1
  fi
  mkdir -p "$host_dir"
  # As in deploy.sh: world-writable until Postgres initialises it and takes ownership.
  if [ -O "$host_dir" ]; then
    chmod 777 "$host_dir"
  fi

  local values=()
  for f in "$EXP_DIR"/projects/*/values.yaml; do
    values+=(-f "$f")
  done
  helm upgrade --install "$RELEASE" "$EXP_DIR/chart" \
    --namespace "$NAMESPACE" --create-namespace \
    "${values[@]}" \
    --wait --timeout 5m
}

down() {
  helm uninstall "$RELEASE" --namespace "$NAMESPACE"
}

seed() {
  load_project "$1"
  load_password

  echo "=== Seeding $DATASET_NAME ==="
  # As the project's role over the pod's local socket, so no port-forward is needed.
  "$PROJECT_DIR/seed.sh" | kubectl exec -i -n "$NAMESPACE" deploy/db-datasets -- \
    psql -v ON_ERROR_STOP=1 -q -U "$DATASET_USERNAME" -d "$DATASET_NAME" > /dev/null

  echo "=== Setting up node project $TEST_PROJECT_NAME ==="
  # fncli finds .dev.env from the current directory; the env set here wins over it.
  cd "$ROOT_DIR"
  CLUSTER_DATASET_HOST="db-datasets.$NAMESPACE.svc" DATASET_PORT=5432 fncli setup-project
}

build() {
  load_project "$1"
  docker build -t "$IMAGE" "$EXP_DIR/$SOURCE_DIR"
  docker push "$IMAGE"
}

run() {
  load_project "$1"
  cd "$ROOT_DIR"
  fncli start-sensor --group all
  local env
  env="$(task_env)"
  echo "Task env: $env"
  if [ "$env" = "{}" ]; then
    TEST_PR_IMAGE="$IMAGE" fncli open-pr --kind watched --merge --watch --timeout "$RUN_TIMEOUT"
  else
    TEST_PR_IMAGE="$IMAGE" TEST_PR_ENV="$env" \
      fncli open-pr --kind watched --merge --watch --timeout "$RUN_TIMEOUT"
  fi
}

# The contract app/definitions/pipes.py gives a task pod, against a port-forward.
run_local() {
  load_project "$1"
  load_password
  local out_dir="$EXP_DIR/results/$1"
  mkdir -p "$out_dir"

  kubectl port-forward -n "$NAMESPACE" svc/db-datasets "$LOCAL_PORT:5432" > /dev/null &
  pf_pid=$!
  trap 'kill $pf_pid' EXIT
  until pg_isready -h localhost -p "$LOCAL_PORT" > /dev/null 2>&1; do
    sleep 1
  done

  local env_args=()
  while IFS= read -r pair; do
    env_args+=(-e "$pair")
  done < <(task_env | python3 -c 'import json, sys; [print(f"{k}={v}") for k, v in json.load(sys.stdin).items()]')

  echo "Results: $out_dir"
  echo "Task env: $(task_env)"
  docker run --rm --network host \
    "${env_args[@]}" \
    -e CONNECTION_STRING="server=localhost;database=$DATASET_NAME;port=$LOCAL_PORT;uid=$DATASET_USERNAME;pwd=$DATASET_PASSWORD;" \
    -e CDM_SCHEMA="$DATASET_SCHEMA" \
    -e WRITE_SCHEMA="$DATASET_SCHEMA_WRITE" \
    -e ARTIFACT_PATH=/artifacts \
    -v "$out_dir:/artifacts" \
    "$IMAGE"
}

case "${1:-}" in
  up) up ;;
  down) down ;;
  seed) seed "${2:-}" ;;
  build) build "${2:-}" ;;
  run) run "${2:-}" ;;
  run-local) run_local "${2:-}" ;;
  *) usage ;;
esac
