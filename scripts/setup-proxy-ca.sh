#!/usr/bin/env bash
set -euo pipefail

###################################################################################
# Federated Node - proxy CA setup
#
# For a machine behind a TLS-intercepting proxy, or one that must trust a private CA:
# check that the proxy and the CA work, then point Docker and this repo's tooling at the
# proxy. The same script serves the host and the dev container. Guide: PROXY_CA_SETUP.md
#
#   ./scripts/setup-proxy-ca.sh [--proxy URL] [--ca-file PATH] [--yes] [--dry-run]
#   ./scripts/setup-proxy-ca.sh --devcontainer [--dry-run]
#   ./scripts/setup-proxy-ca.sh --undo [--yes] [--dry-run]
#
#   --proxy URL     for example http://proxy.example.org:8080; defaults to HTTPS_PROXY.
#                   Optional with --ca-file (a private CA and no proxy).
#   --ca-file PATH  the proxy's CA as a PEM file (one certificate or a bundle), installed
#                   into the system trust store. Without it the system CA bundle is used
#                   as it is: your OS store must already trust the proxy's CA.
#   --devcontainer  what the dev container's initializeCommand runs on the host, without
#                   sudo: reads CUSTOM_CA_FILE and the proxy from .dev.env, else
#                   .generated.env, runs the checks, and copies the bundle to
#                   .devcontainer/proxy-ca.crt (an empty file when neither names a
#                   CUSTOM_CA_FILE: no CA). Writes nothing else.
#   --yes           do not ask
#   --dry-run       show every change and make none
#   --undo          remove what a previous run added (runs no checks)
#
# Every other run, --dry-run and --devcontainer included, first checks, before anything is
# written, that the CA bundle is PEM and, when a proxy is set, that registry-1.docker.io,
# pypi.org and github.com verify through the proxy against the bundle (with --ca-file: the
# bundle plus that CA). With a CA and no proxy only the PEM is checked.
#
# Each step is skipped if it is already done: the CA in the system trust store (only with
# --ca-file), a Docker daemon proxy drop-in (systemd only; Docker restarts, which stops
# running containers), the Docker client proxy in ~/.docker/config.json (image builds and
# containers you start), and two files this script owns and rewrites whole, both gitignored:
# .generated.env (CUSTOM_CA_FILE, the proxy and the CA-bundle variables) and
# k8s/federated-node/generated.values.yaml (the chart's proxy and customCA values). Your own
# .dev.env and dev.values.yaml are never edited, and win over them when loaded.
####################################################################################

cd "$(dirname "$0")/.."

CA_FILE=""
PROXY="${HTTPS_PROXY:-${https_proxy:-}}"
YES=0
DRY=0
UNDO=0
DEVCONTAINER=0
BUNDLE=""
CHECK_BUNDLE=""

# The block an older version of this script kept in .dev.env: --undo removes it.
START="# >>> setup-proxy-ca >>>"
END="# <<< setup-proxy-ca <<<"
GENERATED_ENV=.generated.env
GENERATED_VALUES=k8s/federated-node/generated.values.yaml
GENERATED_HEADER="# Generated by scripts/setup-proxy-ca.sh. Do not edit; rerun the script."
DOCKER_DROPIN=/etc/systemd/system/docker.service.d/http-proxy.conf
DOCKER_CONFIG_FILE="${DOCKER_CONFIG:-$HOME/.docker}/config.json"
DEVCONTAINER_CA=.devcontainer/proxy-ca.crt
LOCAL_NO_PROXY="localhost,127.0.0.1,kind-registry,proxy-docker-hub-registry,proxy-ghcr-registry"
# The variables .generated.env sets (a proxy adds the proxy ones and NO_PROXY).
CA_VARS=(CUSTOM_CA_FILE SSL_CERT_FILE REQUESTS_CA_BUNDLE CURL_CA_BUNDLE GIT_SSL_CAINFO PIP_CERT)
PROXY_VARS=(HTTPS_PROXY https_proxy HTTP_PROXY http_proxy NO_PROXY no_proxy)
GENERATED_VARS=("${CA_VARS[@]}" "${PROXY_VARS[@]}")

# The secret name that scripts/deploy.sh creates from CUSTOM_CA_FILE
source scripts/custom_ca.sh

ok()   { printf '  [%s]   %s\n' "$([ "$DRY" = 1 ] && echo dry || echo ok)" "$*"; }
skip() { printf '  [skip] %s\n' "$*"; }
warn() { printf '  [warn] %s\n' "$*" >&2; }
die()  { printf '  [FAIL] %s\n' "$*" >&2; exit 1; }
usage() { sed -n '5,40p' "$0" | sed 's/^# \{0,1\}//'; }

while [ $# -gt 0 ]; do
  case "$1" in
    --ca-file) CA_FILE="${2:?--ca-file needs a path}"; shift 2 ;;
    --proxy) PROXY="${2:?--proxy needs a URL}"; shift 2 ;;
    --devcontainer) DEVCONTAINER=1; shift ;;
    --yes) YES=1; shift ;;
    --dry-run) DRY=1; shift ;;
    --undo) UNDO=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) usage >&2; die "unknown option: $1" ;;
  esac
done

SUDO=""
[ "$(id -u)" -eq 0 ] || SUDO="sudo"

# Runs a command, or only prints it with --dry-run.
run() {
  if [ "$DRY" = 1 ]; then printf '  would run: %s\n' "$*"; else "$@"; fi
}

confirm() {
  if [ "$YES" = 1 ] || [ "$DRY" = 1 ]; then return 0; fi
  [ -t 0 ] || die "no terminal to ask on: run again with --yes"
  local answer
  read -r -p "  $1 [y/N] " answer
  [[ "$answer" =~ ^[Yy]$ ]]
}

# The last value of a variable in .dev.env (yours, wins), else in .generated.env; empty if none.
env_value() {
  local f v
  for f in .dev.env "$GENERATED_ENV"; do
    [ -f "$f" ] || continue
    v="$(sed -n "s/^\(export \)\{0,1\}$1=//p" "$f" | tail -n 1 | tr -d "\"'")"
    if [ -n "$v" ]; then printf '%s' "$v"; return 0; fi
  done
  return 0
}

# $1 must be a PEM file with at least one certificate; $2 says what it is.
require_pem() {
  [ -s "$1" ] || die "$2: $1 is missing or empty"
  grep -q -e '-----BEGIN CERTIFICATE-----' "$1" \
    || die "$2: $1 is not a PEM certificate: it should contain -----BEGIN CERTIFICATE-----. For a .cer or .der file: openssl x509 -inform der -in file.cer -out ca.pem"
}

# Three hosts verify through the proxy against the bundle (any HTTP status is a pass: the
# TLS handshake is what matters, Docker Hub answers 401 here). With no proxy, which is a CA
# for a private git host and nothing else, the PEM check is all there is.
check_proxy() {
  if [ -z "$PROXY" ]; then
    echo "No proxy set: only the CA is checked, not that any host is reachable through a proxy"
    return 0
  fi
  command -v curl >/dev/null || die "curl is needed for the checks: install it first"
  echo "Checks: the proxy $PROXY and the CA bundle ${CHECK_BUNDLE:-$BUNDLE}"
  local url host rc err why failed=0
  for url in https://registry-1.docker.io/v2/ https://pypi.org/simple/ https://github.com; do
    host="${url#https://}"
    host="${host%%/*}"
    rc=0
    err="$(curl -sS -o /dev/null --proxy "$PROXY" --cacert "${CHECK_BUNDLE:-$BUNDLE}" --connect-timeout 10 "$url" 2>&1)" || rc=$?
    if [ "$rc" = 0 ]; then
      printf '  [ok]   %s verifies through the proxy\n' "$host"
      continue
    fi
    failed=1
    case "$rc" in
      35|51|58|60|77) why="certificate problem: the CA bundle does not match the proxy's certificates (a wrong CA, or an intermediate is missing). Ask IT for the full chain." ;;
      *) why="proxy or connection problem: check the proxy address, and that this machine can reach it." ;;
    esac
    printf '  [FAIL] %s (curl exit %s): %s\n         %s\n' "$host" "$rc" "$err" "$why" >&2
  done
  [ "$failed" = 0 ] || die "a check failed, nothing was changed: see PROXY_CA_SETUP.md, 'If something fails'"
}

###############################################################################
# DEV CONTAINER (runs on the host before the image build)
###############################################################################
if [ "$DEVCONTAINER" = 1 ]; then
  BUNDLE="$(env_value CUSTOM_CA_FILE)"
  if [ -z "$BUNDLE" ]; then
    echo "No CUSTOM_CA_FILE in .dev.env or $GENERATED_ENV: the dev container gets no CA"
    run cp /dev/null "$DEVCONTAINER_CA"
    exit 0
  fi
  require_pem "$BUNDLE" "CUSTOM_CA_FILE in .dev.env or $GENERATED_ENV"
  dev_proxy="$(env_value HTTPS_PROXY)"
  [ -n "$dev_proxy" ] || dev_proxy="$(env_value https_proxy)"
  PROXY="${dev_proxy:-$PROXY}"
  check_proxy
  run cp -f "$BUNDLE" "$DEVCONTAINER_CA"
  ok "$BUNDLE copied to $DEVCONTAINER_CA"
  exit 0
fi

if command -v update-ca-certificates >/dev/null; then
  TRUST_DIR=/usr/local/share/ca-certificates
  TRUST_CMD=update-ca-certificates
  BUNDLE=/etc/ssl/certs/ca-certificates.crt
elif command -v update-ca-trust >/dev/null; then
  TRUST_DIR=/etc/pki/ca-trust/source/anchors
  TRUST_CMD=update-ca-trust
  BUNDLE=/etc/pki/tls/certs/ca-bundle.crt
else
  die "found neither update-ca-certificates nor update-ca-trust: install the ca-certificates package"
fi
TRUST_FILE="$TRUST_DIR/fn-proxy-ca.crt"

NO_PROXY_ALL="$(printf '%s' "$LOCAL_NO_PROXY${NO_PROXY:+,$NO_PROXY}" | tr ',' '\n' | awk 'NF && !seen[$0]++' | paste -sd,)"

restart_docker() {
  echo "  Docker has to restart to use this, and that stops every running container, including a kind cluster."
  if confirm "Restart Docker now?"; then
    run $SUDO systemctl restart docker
    ok "Docker restarted"
  else
    DOCKER_PENDING=1
    warn "restart it yourself when ready: sudo systemctl restart docker"
  fi
}

has_docker_service() {
  [ -d /run/systemd/system ] && systemctl cat docker.service >/dev/null 2>&1
}

# The content of .generated.env: everything the tooling on this machine needs.
env_content() {
  local v
  echo "$GENERATED_HEADER"
  for v in "${CA_VARS[@]}"; do echo "export $v=$BUNDLE"; done
  if [ -n "$PROXY" ]; then
    for v in HTTPS_PROXY https_proxy HTTP_PROXY http_proxy; do echo "export $v=$PROXY"; done
    for v in NO_PROXY no_proxy; do echo "export $v=$NO_PROXY_ALL"; done
  fi
}

# The content of generated.values.yaml: what mise run deploy gives the chart.
values_content() {
  echo "$GENERATED_HEADER"
  if [ -n "$PROXY" ]; then
    echo "proxy:"
    echo "  httpProxy: \"$PROXY\""
    echo "  httpsProxy: \"$PROXY\""
  fi
  echo "customCA:"
  echo "  secretName: $CUSTOM_CA_SECRET"
  echo "  key: ca.crt"
}

# Writes a file this script owns, whole: $1 the path, $2 the content.
write_owned() {
  if [ -f "$1" ] && [ "$(cat "$1")" = "$2" ]; then
    skip "$1 is up to date"
  elif [ "$DRY" = 1 ]; then
    echo "  would write $1:"; echo "$2" | sed 's/^/    /'
  else
    printf '%s\n' "$2" > "$1"
    ok "$1 written"
  fi
}

# Removes the block an older version of this script kept in .dev.env.
drop_old_block() {
  if [ -f .dev.env ] && grep -q "^$START" .dev.env; then
    if [ "$DRY" = 1 ]; then echo "  would remove the setup-proxy-ca block from .dev.env"
    else tmp="$(mktemp)"; sed "\|^$START|,\|^$END|d" .dev.env > "$tmp"; cat "$tmp" > .dev.env; rm -f "$tmp"; fi
    ok "old block removed from .dev.env"
  else
    skip "no setup-proxy-ca block in .dev.env"
  fi
}

###############################################################################
# UNDO
###############################################################################
if [ "$UNDO" = 1 ]; then
  echo "Undoing the proxy CA setup"
  if [ -f "$TRUST_FILE" ]; then
    run $SUDO rm -f "$TRUST_FILE"
    run $SUDO $TRUST_CMD --fresh >/dev/null 2>&1 || run $SUDO $TRUST_CMD >/dev/null
    ok "CA removed from the system trust store"
  else
    skip "no CA from this script in the system trust store"
  fi
  if [ -f "$DOCKER_DROPIN" ]; then
    run $SUDO rm -f "$DOCKER_DROPIN"
    run $SUDO systemctl daemon-reload
    ok "Docker proxy drop-in removed"
    DOCKER_PENDING=0
    restart_docker
  else
    skip "no Docker proxy drop-in"
  fi
  if command -v jq >/dev/null && [ -n "$(jq -c '.proxies.default // empty' "$DOCKER_CONFIG_FILE" 2>/dev/null)" ]; then
    if [ "$DRY" = 1 ]; then echo "  would remove proxies.default from $DOCKER_CONFIG_FILE"
    else tmp="$(mktemp)"; jq 'del(.proxies.default)' "$DOCKER_CONFIG_FILE" > "$tmp" && cat "$tmp" > "$DOCKER_CONFIG_FILE"; rm -f "$tmp"; fi
    ok "proxies.default removed from $DOCKER_CONFIG_FILE"
  else
    skip "no Docker client proxy in $DOCKER_CONFIG_FILE"
  fi
  for f in "$GENERATED_ENV" "$GENERATED_VALUES"; do
    if [ -f "$f" ]; then
      run rm -f "$f"
      ok "$f removed"
    else
      skip "no $f"
    fi
  done
  drop_old_block
  exit 0
fi

###############################################################################
# CHECKS (before anything is written)
###############################################################################
require_pem "$BUNDLE" "the system CA bundle"
[ -n "$PROXY" ] || [ -n "$CA_FILE" ] || die "nothing to set up: give --proxy URL and/or --ca-file PATH, or set HTTPS_PROXY"
if [ -n "$CA_FILE" ]; then
  require_pem "$CA_FILE" "--ca-file"
  command -v openssl >/dev/null || die "openssl is needed to check the CA: install it first"
  CA_FILE="$(cd "$(dirname "$CA_FILE")" && pwd)/$(basename "$CA_FILE")"
  openssl x509 -in "$CA_FILE" -noout >/dev/null 2>&1 || die "openssl cannot read $CA_FILE"
  openssl x509 -in "$CA_FILE" -noout -checkend 0 >/dev/null || die "this CA has expired: ask IT for the current one"
  echo "The CA to trust (the first certificate in $CA_FILE):"
  openssl x509 -in "$CA_FILE" -noout -subject -issuer -enddate -fingerprint -sha256 | sed 's/^/  /'
  if ! openssl x509 -in "$CA_FILE" -noout -text | grep -q "CA:TRUE"; then
    warn "this does not look like a CA certificate (no CA:TRUE). A server certificate will not make the proxy's connections verify: ask IT for the root or issuing CA."
  fi
  echo
  # The trust store does not have the CA yet, so check against what it will hold
  CHECK_BUNDLE="$(mktemp)"
  trap 'rm -f "$CHECK_BUNDLE"' EXIT
  cat "$BUNDLE" "$CA_FILE" > "$CHECK_BUNDLE"
fi
check_proxy
echo
[ -z "$CA_FILE" ] || confirm "Trust this CA on this machine?" || die "stopped, nothing changed"

DOCKER_PENDING=0

###############################################################################
# 1. System trust store
###############################################################################
echo "1. System trust store"
if [ -z "$CA_FILE" ]; then
  skip "no --ca-file: the system bundle $BUNDLE is used as it is"
elif [ -f "$TRUST_FILE" ] && cmp -s "$CA_FILE" "$TRUST_FILE"; then
  skip "CA already trusted"
else
  run $SUDO install -m 0644 "$CA_FILE" "$TRUST_FILE"
  if [ "$DRY" = 1 ]; then echo "  would run: $SUDO $TRUST_CMD"; else $SUDO $TRUST_CMD >/dev/null; fi
  ok "CA added ($TRUST_FILE)"
fi

###############################################################################
# 2. Docker daemon proxy
###############################################################################
echo "2. Docker daemon proxy"
if [ -z "$PROXY" ]; then
  skip "no proxy"
elif ! has_docker_service; then
  warn "Docker is not a systemd service here (Docker Desktop, rootless or a container). Set the proxy in Docker yourself: HTTPS_PROXY=$PROXY NO_PROXY=$NO_PROXY_ALL, then restart Docker."
else
  want="$(printf '[Service]\nEnvironment="HTTP_PROXY=%s"\nEnvironment="HTTPS_PROXY=%s"\nEnvironment="NO_PROXY=%s"' "$PROXY" "$PROXY" "$NO_PROXY_ALL")"
  if [ -f "$DOCKER_DROPIN" ] && [ "$($SUDO cat "$DOCKER_DROPIN")" = "$want" ]; then
    skip "drop-in already set"
  else
    [ ! -f "$DOCKER_DROPIN" ] || run $SUDO cp -a "$DOCKER_DROPIN" "$DOCKER_DROPIN.bak"
    run $SUDO mkdir -p "$(dirname "$DOCKER_DROPIN")"
    if [ "$DRY" = 1 ]; then echo "  would write $DOCKER_DROPIN:"; echo "$want" | sed 's/^/    /'
    else printf '%s\n' "$want" | $SUDO tee "$DOCKER_DROPIN" >/dev/null; fi
    run $SUDO systemctl daemon-reload
    ok "drop-in written ($DOCKER_DROPIN)"
    restart_docker
  fi
fi

###############################################################################
# 3. Docker client proxy: gives every docker build and docker run the proxy variables
###############################################################################
echo "3. Docker client proxy (image builds, and containers you start)"
if [ -z "$PROXY" ]; then
  skip "no proxy"
elif ! command -v jq >/dev/null; then
  warn "jq is not installed. Add this to $DOCKER_CONFIG_FILE yourself: {\"proxies\": {\"default\": {\"httpProxy\": \"$PROXY\", \"httpsProxy\": \"$PROXY\", \"noProxy\": \"$NO_PROXY_ALL\"}}}"
else
  want="$(jq -nc --arg p "$PROXY" --arg n "$NO_PROXY_ALL" '{httpProxy: $p, httpsProxy: $p, noProxy: $n}')"
  have="$(jq -c '.proxies.default // empty' "$DOCKER_CONFIG_FILE" 2>/dev/null || true)"
  if [ "$have" = "$want" ]; then
    skip "already set"
  elif [ "$DRY" = 1 ]; then
    echo "  would set proxies.default in $DOCKER_CONFIG_FILE to: $want"
  else
    mkdir -p "$(dirname "$DOCKER_CONFIG_FILE")"
    [ -f "$DOCKER_CONFIG_FILE" ] || echo '{}' > "$DOCKER_CONFIG_FILE"
    tmp="$(mktemp)"
    jq --argjson p "$want" '.proxies.default = $p' "$DOCKER_CONFIG_FILE" > "$tmp" && cat "$tmp" > "$DOCKER_CONFIG_FILE"
    rm -f "$tmp"
    ok "proxies.default set in $DOCKER_CONFIG_FILE"
  fi
fi

###############################################################################
# 4. The generated files (yours, .dev.env and dev.values.yaml, are never edited)
###############################################################################
echo "4. $GENERATED_ENV and $GENERATED_VALUES"
if [ -f .dev.env ] && grep -q "^$START" .dev.env; then
  warn "an older version of this script left a block in .dev.env, and it wins over $GENERATED_ENV: delete it, from '$START' to '$END'"
fi
overridden=()
for v in "${GENERATED_VARS[@]}"; do
  if [ -f .dev.env ] && sed "\|^$START|,\|^$END|d" .dev.env | grep -q -E "^(export )?$v="; then overridden+=("$v"); fi
done
[ "${#overridden[@]}" = 0 ] || warn "${overridden[*]} set in .dev.env: your value wins over $GENERATED_ENV"
write_owned "$GENERATED_ENV" "$(env_content)"
write_owned "$GENERATED_VALUES" "$(values_content)"

###############################################################################
# 5. Docker
###############################################################################
echo "5. Docker pull"
if [ "$DRY" = 1 ]; then
  echo "  would run a docker pull of ghcr.io/jqlang/jq:latest"
  exit 0
elif [ "$DOCKER_PENDING" = 1 ]; then
  skip "docker pull: restart Docker first, then run this script again"
elif docker info >/dev/null 2>&1; then
  if docker pull -q ghcr.io/jqlang/jq:latest >/dev/null 2>&1; then
    ok "docker pull works"
  else
    die "docker pull ghcr.io/jqlang/jq:latest failed. Try it yourself for the error; then see PROXY_CA_SETUP.md"
  fi
else
  skip "docker pull: Docker is not running or not usable without sudo"
fi
echo
echo "Done. Open a new shell so the variables in $GENERATED_ENV load (mise run loads them itself)."
echo "Next: mise run setup, or mise run cluster up. In the dev container, rebuild it so the CA is picked up."
echo "Image builds get the CA as a build secret (needs BuildKit, Docker 23 or later)."
echo "Known gap: the registry mirrors that mise run cluster up starts do not get the CA yet."
